export type GameType = 'chess' | 'checkers' | 'tictactoe' | 'mafia';
export type BoardGameType = Exclude<GameType, 'mafia'>;
export type Seat = 'first' | 'second';
export type Player = { id: string; name: string; username?: string };
export type GameResult = { winner: Seat | null; reason: string; team?: MafiaTeam };
export type ChessMove = { kind: 'chess'; from: string; to: string; promotion?: 'q' | 'r' | 'b' | 'n' };
export type CheckersMove = { kind: 'checkers'; path: number[] };
export type TicTacToeMove = { kind: 'tictactoe'; cell: number };
export type MafiaMove = { kind: 'mafia'; phase: 'night' | 'day'; round: number; target: string | null };
export type Move = ChessMove | CheckersMove | TicTacToeMove | MafiaMove;
export type CheckerPiece = { seat: Seat; king: boolean };
export type ChessState = { kind: 'chess'; fen: string; moves: string[] };
export type CheckersState = { kind: 'checkers'; board: (CheckerPiece | null)[]; turn: Seat; positions: string[]; quietPlies: number };
export type TicTacToeState = { kind: 'tictactoe'; board: (Seat | null)[]; turn: Seat };
export type MafiaRole = 'mafia' | 'doctor' | 'detective' | 'villager';
export type MafiaTeam = 'mafia' | 'town';
export type MafiaPhase = 'lobby' | 'night' | 'day' | 'finished';
export type MafiaView = {
  kind: 'mafia'; phase: MafiaPhase; round: number; phaseExpiresAt: string | null;
  players: { player: Player; alive: boolean; revealedRole: MafiaRole | null }[];
  yourRole: MafiaRole | null; teammates: string[];
  investigations: { round: number; playerId: string; team: MafiaTeam }[];
  canAct: boolean; hasActed: boolean; yourChoice: string | null;
  votes: Record<string, string | null>;
  events: { round: number; text: string }[];
};
export type BoardGameState = ChessState | CheckersState | TicTacToeState;
export type GameState = BoardGameState | MafiaView;
export type GameSnapshot = {
  id: string; game: GameType; status: 'waiting' | 'active' | 'finished' | 'cancelled';
  creator: Player; opponent: Player | null; state: GameState; turn: Seat;
  legalMoves: Move[]; result: GameResult | null; drawOffer: Seat | null;
  version: number; createdAt: string; updatedAt: string; waitingExpiresAt: string | null;
  history: { number: number; seat: Seat; label: string }[];
  participants?: Player[]; mafiaPhase?: MafiaPhase;
};
// Lobby and Telegram messages do not need boards, legal moves, or move history.
export type GameSummary = Omit<GameSnapshot, 'state' | 'legalMoves' | 'history' | 'drawOffer'>;
export type GameEngine = {
  initialize(): BoardGameState;
  turn(state: GameState): Seat;
  legalMoves(state: GameState): Move[];
  applyMove(state: GameState, move: Move): { state: GameState; label: string };
  result(state: GameState): GameResult | null;
};
export const otherSeat = (seat: Seat): Seat => seat === 'first' ? 'second' : 'first';
export const gameNames: Record<GameType, string> = { chess: 'Chess', checkers: 'Checkers', tictactoe: 'Tic-tac-toe', mafia: 'Mafia' };
export const WAITING_TIMEOUT_MS = 3 * 60_000;
export const MAFIA_MIN_PLAYERS = 5;
export const MAFIA_MAX_PLAYERS = 10;
export const DEMO_PLAYERS = ['Alice', 'Bob', 'Carol', 'Dave', 'Eve', 'Frank', 'Grace', 'Heidi', 'Ivan', 'Judy'] as const;
export const gameResultLabel = (match: Pick<GameSnapshot, 'creator' | 'opponent' | 'result'>): string => match.result?.team ? `${match.result.team === 'mafia' ? 'Mafia' : 'Town'} won` : match.result?.winner ? `${match.result.winner === 'first' ? match.creator.name : match.opponent?.name} won` : 'Draw';
